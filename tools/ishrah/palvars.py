"""Instant colour change (owner, 22 Nov 2026: "changes from settings are slow, like changing colours").
Each colour used to be a whole copy of the styles (pal-<c>.css about 370 KB, mr-pal-<c>.css about 280 KB) that the phone had to download
and apply when the colour was chosen. palettes.py still writes those copies; this script turns them into:
  css/app.pv.css, css/mr.pv.css  the styles once, with every colour that differs between the colours written as var(--pX, <green colour>)
  css/pv.css                     every colour's values: html[data-pal=maroon]{--pa1:#…;…} (a few KB)
so the app loads the styles once and a colour change is only html[data-pal] (index.html head script, IS.setPal): nothing to download.
A colour that is the same in every copy stays as it is. A colour inside url(…) is replaced as the whole url(…) (custom properties cannot
reach inside a url). Run after palettes.py (palettes.py calls it):  python3 tools/ishrah/palvars.py"""
import os, re
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'ishrah', 'css')
TOK = re.compile(r'(url\([^)]*\)|#[0-9a-fA-F]{8}\b|#[0-9a-fA-F]{6}\b|#[0-9a-fA-F]{3,4}\b|rgba?\([^)]*\))')
# base file, var prefix, colour copies (data-pal value: file)
SETS = [('app.css', 'pa', {p: 'pal-%s.css' % p for p in ('teal', 'purple', 'maroon', 'graphite')}),
        ('mr.css', 'pm', {p: 'mr-pal-%s.css' % p for p in ('ocean', 'teal', 'purple', 'maroon', 'graphite')})]


def strip_head(t):
    return re.sub(r'^/\* generated by [^*]*\*/\n', '', t)


def build(base_name, px, copies):
    base = open(os.path.join(ROOT, base_name), encoding='utf-8').read()
    B = TOK.split(base)
    C = {}
    for pal, f in copies.items():
        path = os.path.join(ROOT, f)
        if not os.path.exists(path): continue
        parts = TOK.split(strip_head(open(path, encoding='utf-8').read()))
        if len(parts) != len(B) or any(parts[i] != B[i] for i in range(0, len(B), 2)):
            raise SystemExit('palvars: %s does not line up with %s (run palettes.py first)' % (f, base_name))
        C[pal] = parts
    names, values, out = {}, {p: {} for p in C}, B[:]
    for i in range(1, len(B), 2):
        sig = tuple(C[p][i] for p in sorted(C))
        if all(v == B[i] for v in sig): continue
        key = (B[i],) + sig
        if key not in names:
            n = '--%s%d' % (px, len(names) + 1); names[key] = n
            for p in C:
                if C[p][i] != B[i]: values[p][n] = C[p][i]
        out[i] = 'var(%s,%s)' % (names[key], B[i])
    open(os.path.join(ROOT, base_name.replace('.css', '.pv.css')), 'w', encoding='utf-8').write(
        '/* generated by tools/ishrah/palvars.py from %s: do not edit */\n' % base_name + ''.join(out))
    return values, len(names)


def main():
    blocks, report = {}, []
    for base_name, px, copies in SETS:
        vals, n = build(base_name, px, copies)
        report.append('%s: %d colour slots' % (base_name, n))
        for p, v in vals.items():
            blocks.setdefault(p, []).extend('%s:%s' % kv for kv in v.items())
    css = '/* generated by tools/ishrah/palvars.py: the values of each colour (html[data-pal]) */\n' + ''.join(
        'html[data-pal=%s]{%s}\n' % (p, ';'.join(d)) for p, d in sorted(blocks.items()))
    open(os.path.join(ROOT, 'pv.css'), 'w', encoding='utf-8').write(css)
    print('colour slots: ' + ', '.join(report) + ', pv.css %d KB' % (len(css.encode()) // 1024))


if __name__ == '__main__':
    main()
