"""Colour choices for اشرح لي (owner, 18 Nov 2026: "there must be colour options in Settings").
Writes ishrah/css/pal-<name>.css from ishrah/css/app.css: every blue / navy colour (hue 190-245) is moved to the palette's hue,
keeping its lightness and saturation; gold, red and the other accents stay. The app loads one of these files instead of app.css
(index.html head script, `ish-pal`). Run after every change to css/app.css:  python3 tools/ishrah/palettes.py"""
import colorsys, os, re
ROOT = os.path.join(os.path.dirname(__file__), '..', '..', 'ishrah', 'css')
# name: (target hue in degrees or None, saturation factor)
PALS = {'teal': (183, 1.0), 'green': (150, .72), 'purple': (262, .85), 'maroon': (345, .85), 'graphite': (None, .12)}
SRC = 216  # the blue the app was drawn in

def shift(r, g, b, hue, sf):
    h, l, s = colorsys.rgb_to_hls(r / 255, g / 255, b / 255)
    if s < .12 or not (190 / 360 <= h <= 245 / 360):
        return None
    if hue is not None:
        h = (h + (hue - SRC) / 360) % 1
    s = min(1, s * sf)
    return tuple(round(x * 255) for x in colorsys.hls_to_rgb(h, l, s))

def conv(css, hue, sf):
    def hx(m):
        t = m.group(1)
        if len(t) == 3: t = ''.join(c * 2 for c in t)
        n = shift(int(t[0:2], 16), int(t[2:4], 16), int(t[4:6], 16), hue, sf)
        return m.group(0) if n is None else '#%02x%02x%02x' % n
    def rg(m):
        r, g, b = (int(x) for x in m.group(2, 3, 4))
        n = shift(r, g, b, hue, sf)
        return m.group(0) if n is None else '%s(%d,%d,%d%s' % (m.group(1), n[0], n[1], n[2], m.group(5))
    css = re.sub(r'#([0-9a-fA-F]{6}|[0-9a-fA-F]{3})\b', hx, css)
    css = re.sub(r'(rgba?)\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)(\s*[,)])', rg, css)
    return css.replace('url(../img/', 'url(../img/')

# Main accent and highlight stay readable on the new warm paper surfaces.
ACCENTS = {'teal': ('#0b6870', '#397e86'), 'green': ('#356345', '#4c7758'),
           'purple': ('#60458a', '#746197'), 'maroon': ('#823f53', '#946176'),
           'graphite': ('#4b585b', '#687678')}

src = open(os.path.join(ROOT, 'app.css'), encoding='utf-8').read()
for name, (hue, sf) in PALS.items():
    accent, highlight = ACCENTS[name]
    css = conv(src, hue, sf).replace('--medical-accent:#0b6d63', '--medical-accent:' + accent)
    css = css.replace('--medical-highlight:#31877a', '--medical-highlight:' + highlight)
    open(os.path.join(ROOT, 'pal-%s.css' % name), 'w', encoding='utf-8').write('/* generated by tools/ishrah/palettes.py from app.css: do not edit */\n' + css)
print('wrote', ', '.join('pal-%s.css' % n for n in PALS))

# the logo follows the colour too (owner, 18 Nov 2026: "the platform colour should affect even the logo"):
# its navy parts (background of the picture logo, rod and snake of the drawn one) take the colour; the gold stays.
IMG = os.path.join(ROOT, '..', 'img')
from PIL import Image
hero = Image.open(os.path.join(IMG, 'logo_hero.webp')).convert('RGB')
svg = open(os.path.join(IMG, 'logo_gold.svg'), encoding='utf-8').read()
for name, (hue, sf) in PALS.items():
    im = hero.copy(); px = im.load(); cache = {}
    for y in range(im.height):
        for x in range(im.width):
            c = px[x, y]
            if c not in cache:
                cache[c] = shift(*c, hue, sf) or c
            px[x, y] = cache[c]
    im.save(os.path.join(IMG, 'logo_hero_%s.webp' % name), quality=90)
    open(os.path.join(IMG, 'logo_gold_%s.svg' % name), 'w', encoding='utf-8').write(conv(svg, hue, sf))
print('logos written')



