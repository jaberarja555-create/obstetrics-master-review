def _lv(prefix, levels, emq=None):
    d = {'%s-%d' % (prefix, i + 1): int(x) for i, x in enumerate(levels)}
    for name, lv in (emq or {}).items():
        for k, x in enumerate(lv): d['%s#%d' % (name, k)] = int(x)
    return d
